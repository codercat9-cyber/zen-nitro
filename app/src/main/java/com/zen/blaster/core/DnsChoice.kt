package com.zen.blaster.core

// ============================================================================
//  Какой резолвер использовать.
//
//  Раньше был зашит один Cloudflare. Пока он открыт — вопросов нет, а в день,
//  когда оператор его прикрыл, приложение осталось вообще без DNS: ни имя
//  ноды разрешить, ни сайт открыть. Один жёстко вбитый адрес — это не выбор
//  разработчика, это единственная точка отказа.
//
//  Адреса — ЧИСЛОВЫЕ, а не доменные, и это принципиально: чтобы разрешить
//  имя резолвера, нужен резолвер. По IP такой петли нет.
//
//  Каждый проверен живым бинарным DNS-запросом (RFC 8484) ПО АДРЕСУ: сертификат
//  обязан быть выписан на сам IP, иначе ядро его отвергнет. Это и есть главное
//  сито — у многих резолверов сертификат только на имя (Mullvad, NextDNS,
//  Wikimedia, LibreDNS…), и по адресу они не работают вовсе.
//  Порядок в списке менять нельзя — в настройках хранится номер.
// ============================================================================
object DnsChoice {

    data class Server(val name: String, val url: String, val hint: String)

    // ПОРЯДОК В СПИСКЕ МЕНЯТЬ НЕЛЬЗЯ — в настройках хранится НОМЕР, и сдвиг
    // молча переключил бы людям резолвер. Новые добавляются только в конец.
    //
    // Cloudflare и Google стоят первыми по историческим причинам, но выбор по
    // умолчанию с них снят (см. PREFERRED): с августа 2026 ТСПУ бьёт точечно
    // по лидерам рынка — рвёт TLS-рукопожатие к 1.1.1.1 и 8.8.8.8 по их
    // адресам и SNI. Соединение при этом устанавливается, а на обмене ключами
    // подвисает, поэтому со стороны это выглядит как «интернет есть, но сайты
    // не открываются»: канал живой, а имена не разрешаются.
    val LIST = listOf(
        Server("Cloudflare", "https://1.1.1.1/dns-query",
            "быстрый, но с августа 2026 его режут первым"),
        Server("Google", "https://8.8.8.8/dns-query",
            "видит все ваши запросы, и его тоже режут"),
        Server("Яндекс", "https://77.88.8.8/dns-query",
            "внутри России — работает, когда режут заграничное"),
        Server("AdGuard", "https://94.140.14.14/dns-query",
            "режет рекламу и слежку, пока не под ударом"),
        Server("Quad9", "https://9.9.9.9/dns-query",
            "швейцарский, блокирует вредоносные адреса"),
        // Номер 5 был Mullvad, номер 7 — dns0.eu. Оба не работали НИКОГДА:
        // у Mullvad сертификат выписан только на имя dns.mullvad.net, а мы
        // ходим по адресу — проверка сертификата падала у всех; dns0.eu
        // закрылся. Номера заморожены, поэтому на их места встали живые
        // резолверы того же толка: у кого был выбран мёртвый, теперь работает.
        // (Проверено 14 октября 2026 напрямую из России и через границу.)
        Server("DNS.SB", "https://185.222.222.222/dns-query",
            "немецкий, без журналов, о нём мало кто знает"),
        // Был 76.76.2.0: сертификат ControlD выписан на .2.11/.2.22/.10.11/
        // .10.22, а на .2.0 — нет. 14.10.2026 у оператора с ним весь DNS в
        // туннеле сыпался ошибкой проверки сертификата, а наш же ловец
        // «сервер представляется чужим именем» принял это за беду НОДЫ.
        Server("ControlD", "https://76.76.2.11/p0",
            "малоизвестный — потому и живой"),
        Server("Switch", "https://130.59.31.248/dns-query",
            "швейцарская академическая сеть, в чёрные списки не попадает"),
        // --- добавлены 14.10.2026 ---
        // Запасные адреса тех же служб. ТСПУ режет крупных по конкретным
        // адресам (1.1.1.1, 8.8.8.8, 9.9.9.9) — второй адрес того же сервиса
        // нередко проходит, когда основной уже прикрыт.
        Server("Quad9 · второй адрес", "https://149.112.112.112/dns-query",
            "тот же Quad9 через запасной вход"),
        Server("DNS.SB · второй адрес", "https://45.11.45.11/dns-query",
            "тот же DNS.SB через запасной вход"),
        Server("OpenDNS", "https://208.67.222.222/dns-query",
            "американский Cisco, режут его редко"),
        Server("DNSPod", "https://1.12.12.12/dns-query",
            "китайский Tencent: в России его не трогают, но и доверять ему как своему не стоит"),
        Server("Яндекс · второй адрес", "https://77.88.8.1/dns-query",
            "внутри России, запасной вход"),
        Server("Cloudflare · второй адрес", "https://1.0.0.1/dns-query",
            "тот же Cloudflare, его второй адрес режут реже"),
        Server("Google · второй адрес", "https://8.8.4.4/dns-query",
            "тот же Google, второй адрес"),
    )

    // Что предлагаем по умолчанию — НЕ первый в списке.
    //
    // Отдельная величина именно потому, что порядок в LIST заморожен: сменить
    // умолчание, не трогая сохранённые у людей номера, иначе нельзя.
    const val PREFERRED = 4          // Quad9

    // Резолверы для автоперебора, когда выбранный молчит. Сначала те, по
    // которым ТСПУ пока не бьёт, — гиганты в конце, как последняя надежда.
    val FALLBACK_ORDER = listOf(4, 8, 5, 9, 7, 6, 3, 10, 11, 2, 12, 13, 14, 0, 1)

    const val CUSTOM = -1

    // Системный резолвер оператора.
    //
    // Обычно он худший выбор: оператор видит все имена открытым текстом.
    // Но в день жёстких ограничений он единственный, кто отвечает — DoH
    // режут первым делом, а системный оставляют, иначе у людей перестанут
    // открываться и разрешённые сайты. Проверено 14.08.2026 на Tele2 и МТС:
    // все пять DoH молчали по 8 секунд, системный резолвил мгновенно.
    const val SYSTEM = -2

    // АВТО — берём резолвер, который назвала сама подписка.
    //
    //  Провайдер знает про свои ноды то, чего не знаем мы: какой DNS отдаёт
    //  для них НЕ подменённые адреса. Подписки в формате конфига несут это
    //  прямо в секции dns, и глупо гадать, когда ответ уже прислали.
    //
    //  Адрес живёт в настройках (Prefs.autoDns) и обновляется при каждой
    //  загрузке подписок. Пока никто ничего не назвал, «Авто» ведёт себя как
    //  выбор по умолчанию — то есть хуже не делает.
    const val AUTO = -3

    @Volatile var fromSub: String = ""

    // Известные резолверы по именам.
    //
    //  Провайдеры пишут в конфиге доменное имя («https://cloudflare-dns.com/
    //  dns-query»), и это возвращает ту самую петлю, ради которой весь наш
    //  список числовой: чтобы спросить имя у резолвера, надо сначала узнать
    //  адрес самого резолвера. Для известных имён адрес мы и так знаем —
    //  подставляем его и петли не возникает. Незнакомое имя оставляем как
    //  есть: разрешится системным резолвером по физической сети.
    private val BY_NAME = mapOf(
        "cloudflare-dns.com" to "1.1.1.1",
        "one.one.one.one" to "1.1.1.1",
        "dns.google" to "8.8.8.8",
        "dns.quad9.net" to "9.9.9.9",
        "dns.adguard-dns.com" to "94.140.14.14",
        "dns.adguard.com" to "94.140.14.14",
        // Mullvad сюда не вносим: его сертификат не на адрес, а на имя.
        "freedns.controld.com" to "76.76.2.11",
        "dns.sb" to "185.222.222.222",
        "doh.dns.sb" to "185.222.222.222",
        "dns.switch.ch" to "130.59.31.248",
        "doh.opendns.com" to "208.67.222.222",
        "doh.pub" to "1.12.12.12",
        "common.dot.dns.yandex.net" to "77.88.8.8",
    )

    fun autoUrl(): String {
        val raw = fromSub.trim()
        if (raw.isEmpty()) return LIST[PREFERRED].url
        val host = raw.removePrefix("https://").substringBefore('/')
        val ip = BY_NAME[host.lowercase()] ?: return raw
        return raw.replaceFirst(host, ip)
    }

    // ------------------------------------------------------------------
    //  ДВА РАЗНЫХ РЕЗОЛВА, И ТРЕБОВАНИЯ У НИХ ПРОТИВОПОЛОЖНЫЕ
    //
    //  1. ДО туннеля. Разрешить адрес самой ноды, пока канала ещё нет.
    //     Запрос идёт по физической сети, открыто, через оператора — и здесь
    //     Cloudflare с Google худший выбор: с августа 2026 ТСПУ рвёт к ним
    //     TLS-рукопожатие по адресу и SNI. Ровно ради этого случая гиганты
    //     убраны из начала списка, а все адреса числовые.
    //
    //  2. ВНУТРИ туннеля. Разрешать имена сайтов, когда канал уже поднят.
    //     Запрос идёт зашифрованным до сервера, ТСПУ его не видит, и тот же
    //     Cloudflare здесь отличен: он быстрый и его не подменяют. Именно
    //     для этой задачи провайдер и кладёт свой резолвер в подписку.
    //
    //  Раньше выбор был один на оба случая — и совет подписки («Авто»)
    //  тащил Cloudflare туда, где его режут. Теперь развязано: явный выбор
    //  человека уважается везде, а «Авто» советует только туннелю; до
    //  туннеля в этом режиме идёт заведомо живучий.
    // ------------------------------------------------------------------

    // Чем разрешать имена ВНУТРИ поднятого туннеля. Сюда и идёт совет подписки.
    //
    // «Системный» внутри туннеля НЕ применяем никогда. Его выбирают в дни,
    // когда оператор режет шифрованный DNS, — но режет он то, что видит, а
    // запрос внутри туннеля он не видит. Зато «local» в конфиге ядра означал,
    // что имена ВСЕХ сайтов, открытых через VPN, уходят оператору открытым
    // текстом: он видит, куда человек ходит, и может подменить ответ, после
    // чего заблокированный сайт не откроется даже через VPN. Так было до
    // 1 октября 2026 — у самого оператора «Системный» и стоял.
    fun tunnelUrl(i: Int, custom: String): String =
        if (i == SYSTEM) LIST[PREFERRED].url else url(i, custom)

    // Как назвать резолвер туннеля человеку — с учётом подмены выше.
    fun tunnelName(i: Int, custom: String): String =
        if (i == SYSTEM) "${LIST[PREFERRED].name} (системный — только до туннеля)"
        else name(i, custom)

    // Чем разрешать адрес ноды, пока туннеля ещё нет.
    fun preUrl(i: Int, custom: String): String =
        if (i == AUTO) LIST[PREFERRED].url else url(i, custom)

    fun preName(i: Int, custom: String): String =
        if (i == AUTO) LIST[PREFERRED].name else name(i, custom)

    // url для конфига ядра. i == CUSTOM → берём то, что вписал человек.
    // Для SYSTEM отдаём local — ядро sing-box так обозначает системный резолвер.
    fun url(i: Int, custom: String): String = when {
        i == SYSTEM -> "local"
        i == AUTO -> autoUrl()
        i == CUSTOM || i >= LIST.size -> custom.trim().ifEmpty { LIST[0].url }
        i < 0 -> LIST[0].url
        else -> LIST[i].url
    }

    fun name(i: Int, custom: String): String = when {
        i == SYSTEM -> "Системный"
        i == AUTO ->
            if (fromSub.isEmpty()) "Авто (подписка молчит → ${LIST[PREFERRED].name})"
            else "Авто: " + autoUrl().removePrefix("https://").substringBefore('/')
        i == CUSTOM || i >= LIST.size ->
            custom.trim().ifEmpty { LIST[0].name }.removePrefix("https://").substringBefore('/')
        i < 0 -> LIST[0].name
        else -> LIST[i].name
    }

    // Адрес, по которому потом проверяем живость. Из URL достаём хост.
    fun host(i: Int, custom: String): String =
        url(i, custom).removePrefix("https://").substringBefore('/')
}
